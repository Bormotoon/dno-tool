"""Естественная (natural) сортировка строк с учётом чисел.

Обычная лексикографическая сортировка ставит ".10" перед ".2", потому что
сравнивает символы по одному: '1' < '2'. Natural sort разбивает строку на
чередующиеся текстовые и числовые токены, чтобы ".2" шла после ".1", но
перед ".10".
"""

import re

_TOKEN_RE = re.compile(r"(\d+)")


def natural_key(s: str) -> list:
    """Ключ сортировки для :func:`sorted` / :meth:`list.sort`.

    Разбивает строку на токены ``[str, int, str, int, ...]`` (приведённую к
    нижнему регистру для case-insensitive порядка). Числовые токены
    сравниваются как ``int``, текстовые — как строки.

    Пример::

        sorted([".1", ".10", ".2", ".20"], key=natural_key)
        # ['.1', '.2', '.10', '.20']
    """
    return [
        int(part) if part.isdigit() else part
        for part in _TOKEN_RE.split((s or "").lower())
    ]
