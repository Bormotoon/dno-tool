def description_for(filename: str, group: str, key: str, fallback: str) -> str:
    """Объяснить конкретную роль, не выводя назначение неизвестного ключа из имени."""
    if group == "KDE Action Restrictions" and key in RESTRICTIONS:
        return RESTRICTIONS[key]
    if group == "General" and key in FONT_ROLES and filename == "kdeglobals":
        return (
            "Семейство, размер и начертание шрифта для "
            + FONT_ROLES[key]
            + ". Шрифты выбираются из ресурсов удалённого компьютера; приложения могут иметь собственные настройки."
        )
    if group.startswith("Colors:") and key in COLOR_ROLES:
        area = COLOR_GROUPS.get(group.partition(":")[2], group)
        return (
            "Цвет для "
            + area
            + ": "
            + COLOR_ROLES[key]
            + ". Формат — R,G,B или R,G,B,A, компоненты от 0 до 255; прозрачность поддерживается не всеми приложениями."
        )
    return DESCRIPTIONS.get((filename, key), fallback)
